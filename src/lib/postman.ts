import type { ApiSuite } from "@/lib/ai/schemas"

/** Builds a Postman Collection v2.1 deterministically from the AI-detected endpoints and assertions. */
export function toPostmanCollection(name: string, suite: ApiSuite) {
  const authHeader =
    suite.auth_scheme === "none"
      ? []
      : [
          suite.auth_scheme === "api_key"
            ? { key: "X-API-Key", value: "{{apiKey}}", type: "text" }
            : { key: "Authorization", value: suite.auth_scheme === "basic" ? "Basic {{basicAuth}}" : "Bearer {{token}}", type: "text" },
        ]

  const items = suite.endpoints.map((ep) => ({
    name: `${ep.method} ${ep.path} - ${ep.name}`,
    description: `${ep.description}\n\nTraces: ${ep.requirement_codes.join(", ")}`,
    item: ep.tests.map((t) => {
      const segments = ep.path.replace(/^\//, "").split("/").filter(Boolean)
      const rawPath = segments.map((s) => (s.startsWith(":") ? `{{${s.slice(1)}}}` : s))
      const query = t.query.map((q) => ({ key: q.key, value: q.value }))
      const qs = query.length ? `?${query.map((q) => `${q.key}=${q.value}`).join("&")}` : ""
      const exec = [
        `pm.test("Status is ${t.expected_status}", () => pm.response.to.have.status(${t.expected_status}));`,
        ...t.assertions
          .filter((a) => a.kind !== "status")
          .map((a) => {
            const path = a.target.replace(/^\$\.?/, "")
            switch (a.kind) {
              case "json_path_exists":
                return `pm.test("${path} exists", () => pm.expect(_.get(pm.response.json(), ${JSON.stringify(path)})).to.not.be.undefined);`
              case "json_path_equals":
                return `pm.test("${path} equals ${a.expected.replace(/"/g, "'")}", () => pm.expect(String(_.get(pm.response.json(), ${JSON.stringify(path)}))).to.eql(${JSON.stringify(a.expected)}));`
              case "header_exists":
                return `pm.test("Header ${a.target}", () => pm.response.to.have.header(${JSON.stringify(a.target)}));`
              case "response_time_below":
                return `pm.test("Response time < ${Number(a.expected) || 1000}ms", () => pm.expect(pm.response.responseTime).to.be.below(${Number(a.expected) || 1000}));`
              default:
                return ""
            }
          })
          .filter(Boolean),
      ]
      return {
        name: t.name,
        event: [{ listen: "test", script: { type: "text/javascript", exec } }],
        request: {
          method: ep.method,
          header: [...authHeader, ...(t.request_body ? [{ key: "Content-Type", value: "application/json", type: "text" }] : [])],
          ...(t.request_body ? { body: { mode: "raw", raw: prettyJson(t.request_body), options: { raw: { language: "json" } } } } : {}),
          url: { raw: `{{baseUrl}}/${rawPath.join("/")}${qs}`, host: ["{{baseUrl}}"], path: rawPath, query },
        },
      }
    }),
  }))

  return {
    info: {
      name: `${name} API Suite`,
      description: "Generated by TestForge AI",
      schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    },
    variable: [
      { key: "baseUrl", value: suite.base_url || "https://api.example.com" },
      { key: "token", value: "" },
    ],
    item: items,
  }
}

function prettyJson(raw: string) {
  try {
    return JSON.stringify(JSON.parse(raw), null, 2)
  } catch {
    return raw
  }
}
