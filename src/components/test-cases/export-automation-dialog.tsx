"use client"

import { useState } from "react"
import { Code2, FileArchive, Loader2, Sparkles, Terminal } from "lucide-react"
import { exportAutomation, type Framework } from "@/app/actions/test-cases"
import { CodeViewer } from "@/components/shared/code-viewer"
import type { AutomationCode } from "@/lib/ai/schemas"
import { Button } from "@/components/ui/button"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/components/ui/dialog"
import { useServerAction } from "@/hooks/use-server-action"
import { downloadZip } from "@/lib/download"
import { usePrefs } from "@/lib/store"
import { cn } from "@/lib/utils"

const MAX_EXPORT = 10

const FRAMEWORKS: { id: Framework; name: string; lang: string; accent: string }[] = [
  { id: "playwright", name: "Playwright", lang: "TypeScript", accent: "from-emerald-500/20 to-emerald-500/5" },
  { id: "cypress", name: "Cypress", lang: "TypeScript", accent: "from-teal-500/20 to-teal-500/5" },
  { id: "selenium", name: "Selenium", lang: "Python · pytest", accent: "from-amber-500/20 to-amber-500/5" },
]

export function ExportAutomationDialog({ projectId, projectKey, testCaseIds }: { projectId: string; projectKey: string; testCaseIds: string[] }) {
  const [open, setOpen] = useState(false)
  const { framework, setFramework } = usePrefs()
  const [result, setResult] = useState<{ framework: Framework; code: AutomationCode } | null>(null)
  const [activeFile, setActiveFile] = useState(0)
  const { run, pending } = useServerAction((ids: string[], fw: Framework) => exportAutomation(projectId, ids, fw), {
    success: (d) => `Generated ${d.files.length} files`,
  })

  async function generate() {
    const code = await run(testCaseIds, framework)
    if (code) {
      setResult({ framework, code })
      setActiveFile(0)
    }
  }

  const files = result?.code.files ?? []

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button disabled={testCaseIds.length === 0}>
          <Code2 /> Export to Automation
          {testCaseIds.length > 0 && <span className="rounded bg-primary-foreground/20 px-1.5 text-xs">{testCaseIds.length}</span>}
        </Button>
      </DialogTrigger>
      <DialogContent className="max-h-[92vh] overflow-y-auto sm:max-w-5xl">
        <DialogHeader>
          <DialogTitle>Export to automation</DialogTitle>
          <DialogDescription>
            Convert {testCaseIds.length} selected test case{testCaseIds.length === 1 ? "" : "s"} into runnable, page-object based code.
          </DialogDescription>
        </DialogHeader>

        <div className="grid gap-3 sm:grid-cols-3">
          {FRAMEWORKS.map((f) => (
            <button
              key={f.id}
              type="button"
              onClick={() => setFramework(f.id)}
              className={cn(
                "rounded-lg border bg-gradient-to-br p-4 text-left transition-all",
                f.accent,
                framework === f.id ? "border-primary ring-2 ring-primary/30" : "hover:border-primary/40",
              )}
            >
              <div className="font-semibold">{f.name}</div>
              <div className="text-xs text-muted-foreground">{f.lang}</div>
            </button>
          ))}
        </div>

        <div className="flex items-center justify-end gap-2">
          {testCaseIds.length > MAX_EXPORT && (
            <span className="mr-auto text-xs text-destructive">Select at most {MAX_EXPORT} test cases per export.</span>
          )}
          {result && (
            <Button
              variant="outline"
              onClick={() =>
                downloadZip(`${projectKey.toLowerCase()}-${result.framework}-tests.zip`, [
                  ...files,
                  {
                    path: "README.md",
                    language: "markdown",
                    content: `# ${projectKey} ${result.framework} suite\n\nGenerated by TestForge AI.\n\n## Setup\n\n${result.code.setup_instructions
                      .map((s) => `- \`${s}\``)
                      .join("\n")}\n\n## Notes\n\n${result.code.notes.map((n) => `- ${n}`).join("\n")}\n`,
                  },
                ])
              }
            >
              <FileArchive /> Download ZIP
            </Button>
          )}
          <Button onClick={generate} disabled={pending || testCaseIds.length === 0 || testCaseIds.length > MAX_EXPORT}>
            {pending ? <Loader2 className="animate-spin" /> : <Sparkles />}
            {result ? "Regenerate" : "Generate code"}
          </Button>
        </div>

        {pending && !result && (
          <div className="flex flex-col items-center gap-3 rounded-lg border border-dashed py-14 text-sm text-muted-foreground">
            <Loader2 className="size-6 animate-spin text-primary" />
            Writing page objects and specs…
          </div>
        )}

        {result && (
          <div className="grid gap-4 lg:grid-cols-[220px_1fr]">
            <div className="space-y-4">
              <div>
                <div className="mb-2 text-xs font-medium text-muted-foreground">Files</div>
                <ul className="space-y-0.5">
                  {files.map((f, i) => (
                    <li key={f.path}>
                      <button
                        type="button"
                        onClick={() => setActiveFile(i)}
                        className={cn(
                          "w-full truncate rounded-md px-2 py-1.5 text-left font-mono text-xs",
                          i === activeFile ? "bg-accent text-accent-foreground" : "text-muted-foreground hover:bg-muted",
                        )}
                        title={f.path}
                      >
                        {f.path}
                      </button>
                    </li>
                  ))}
                </ul>
              </div>
              {result.code.setup_instructions.length > 0 && (
                <div>
                  <div className="mb-2 flex items-center gap-1.5 text-xs font-medium text-muted-foreground">
                    <Terminal className="size-3.5" /> Setup
                  </div>
                  <ul className="space-y-1">
                    {result.code.setup_instructions.map((s, i) => (
                      <li key={i} className="rounded bg-muted px-2 py-1 font-mono text-[11px] break-all">
                        {s}
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
            <div className="min-w-0 space-y-3">
              {files[activeFile] && <CodeViewer code={files[activeFile].content} filename={files[activeFile].path} maxHeight="26rem" />}
              {result.code.notes.length > 0 && (
                <ul className="list-disc space-y-1 rounded-lg border bg-muted/30 p-3 pl-7 text-xs text-muted-foreground">
                  {result.code.notes.map((n, i) => (
                    <li key={i}>{n}</li>
                  ))}
                </ul>
              )}
            </div>
          </div>
        )}
      </DialogContent>
    </Dialog>
  )
}
